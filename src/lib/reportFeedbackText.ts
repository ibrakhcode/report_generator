import { monthLabel } from '@/lib/reportPosts';

export function parseRecipientList(value: string) {
  return Array.from(
    new Set(
      value
        .split(/[,;\n]+/)
        .map((item) => item.trim().toLowerCase())
        .filter((item) => item.includes('@'))
    )
  );
}

export function escapeHtml(value: string) {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

export function reportEmailHtml(text: string, feedbackUrl: string, month: string) {
  const period = monthLabel(month);
  const button = `<a href="${escapeHtml(feedbackUrl)}" style="display:inline-block;background:#0f766e;color:#fff;padding:10px 18px;border-radius:8px;text-decoration:none;font-weight:bold">Feedback</a>`;
  const blocks = text
    .trim()
    .split(/\n\s*\n/)
    .map((block) => {
      let safe = escapeHtml(block.trim()).replace(/\n/g, '<br/>');
      if (feedbackUrl) safe = safe.split(escapeHtml(feedbackUrl)).join(`<br/>${button}`);
      return `<p>${safe}</p>`;
    });
  const hasButton = !feedbackUrl || blocks.some((item) => item.includes(button));
  return `
    <div style="font-family:Arial,sans-serif;color:#0f172a;line-height:1.6;max-width:640px">
      ${blocks.join('')}
      ${hasButton ? '' : `<p>${button}</p>`}
      <p style="font-size:12px;color:#64748b">ICT Monthly Report — ${period}</p>
    </div>
  `;
}

export function autoReportEmail(month: string, feedbackUrl: string) {
  const period = monthLabel(month);
  const text = [
    'Dear Sir/Madam,',
    '',
    `I have attached my ICT monthly report for ${period}.`,
    'Please review and confirm.',
    '',
    'This report is autogenerated by Ibrahim Agent by combining all tickets, activities recorded, projects and incidents.',
    '',
    'I confirm that this reporting HAS BEEN verified by Ibrahim himself and approved before it was sent.',
    '',
    `For any query click Feedback: ${feedbackUrl}`
  ].join('\n');
  const html = reportEmailHtml(text, feedbackUrl, month);
  return { text, html, subject: `ICT Monthly Report — ${period}` };
}
